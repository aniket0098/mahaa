"""Enumerations for the Learn service domain.

Each one is a PostgreSQL ``CHECK`` constraint backed by a Python enum, so an
invalid value is rejected by the database even if it arrives from a client the
schema layer never saw. The members are named after their database values, so
the stored text is exactly the value in the specification's ``CHECK in (...)``.

``native_enum=False`` is deliberate. A native PostgreSQL ``ENUM`` type
cannot be extended cheaply -- adding a value means ``ALTER TYPE`` and a
lock -- whereas the specification's vocabularies are expected to grow. A
``VARCHAR`` with a ``CHECK`` gives identical database-level enforcement and
a value is just a code change.

``create_constraint=True`` is explicit because SQLAlchemy 2.0 defaults it to
``False``, which would silently ship an unconstrained column. ``values_callable``
makes the constraint list the *values* rather than the member names, so the
database text matches the specification's ``CHECK in (...)`` exactly.
"""

from __future__ import annotations

from enum import StrEnum

from sqlalchemy import Enum as SAEnum


def pg_enum[E: StrEnum](enum_cls: type[E], constraint_name: str) -> SAEnum:
    """``VARCHAR`` column plus a real ``CHECK`` constraint.

    ``native_enum=False`` is deliberate. A native PostgreSQL ``ENUM`` type
    cannot be extended cheaply -- adding a value means ``ALTER TYPE`` and a
    lock -- whereas the specification's vocabularies are expected to grow. A
    ``VARCHAR`` with a ``CHECK`` gives identical database-level enforcement and
    a value is just a code change.

    ``create_constraint=True`` is explicit because SQLAlchemy 2.0 defaults it to
    ``False``, which would silently ship an unconstrained column. ``values_callable``
    makes the constraint list the *values* rather than the member names, so the
    database text matches the specification's ``CHECK in (...)`` exactly.
    """

    return SAEnum(
        enum_cls,
        name=constraint_name,
        native_enum=False,
        create_constraint=True,
        validate_strings=True,
        values_callable=lambda members: [member.value for member in members],
    )


class UserRole(StrEnum):
    """``users.role``. ``admin`` exists but is never self-registerable."""

    CANDIDATE = "candidate"
    EMPLOYER = "employer"
    COLLEGE = "college"
    ADMIN = "admin"


class UserStatus(StrEnum):
    """``users.status``.

    ``deactivated`` is the mobile client's soft pause: signing in again
    reactivates the account. Nothing is deleted.
    """

    ACTIVE = "active"
    SUSPENDED = "suspended"
    DEACTIVATED = "deactivated"


class SkillLevel(StrEnum):
    """``courses.skill_level``."""

    BEGINNER = "beginner"
    INTERMEDIATE = "intermediate"
    ADVANCED = "advanced"
    EXPERT = "expert"


class CourseStatus(StrEnum):
    """``courses.status`` -- the Learning Hub publication state.

    Mirrors ``OpportunityStatus``'s reasoning: a course the platform can show
    needs a non-shown state to exclude, and the list query filters on it **in
    SQL** so a draft can never leak through a missed Python-side check.
    ``archived`` is deliberately absent until there is a real archive action.
    """

    DRAFT = "draft"
    PUBLISHED = "published"


class CourseVisibility(StrEnum):
    """``courses.visibility`` -- same two values as ``OpportunityVisibility``.

    ``unlisted`` is the honest second value: reachable by direct id, absent from
    the catalogue, so the column is a real discriminator rather than a constant.
    """

    PUBLIC = "public"
    UNLISTED = "unlisted"


class LectureKind(StrEnum):
    """``course_lectures.kind`` -- what a lecture can carry, decided at write time.

    The three kinds are exactly what the existing infrastructure can honestly
    serve today: ``hosted_video`` is a `media_assets` video row (the 10 MB
    database-backed pipeline), ``external_video`` is a validated ``https://``
    URL to a third-party host (no upload, no storage), and ``reading`` is
    either an uploaded PDF media row or a linked reading. A kind whose source
    cannot be represented would render as an empty player forever, so the set
    is closed.

    The members use the **database text** (``'hosted_video'``, ``'external_video'``,
    ``'reading'``) because PostgreSQL enforces them via ``CHECK`` constraints
    generated by the main backend.
    """

    HOSTED_VIDEO = "hosted_video"
    EXTERNAL_VIDEO = "external_video"
    READING = "reading"


class LectureStatus(StrEnum):
    """``course_lectures.status`` -- a lecture inside a published course can still
    be an unpublished draft, which is why this is a column and not a
    consequence of the parent's status.
    """

    DRAFT = "draft"
    PUBLISHED = "published"


class EnrollmentStatus(StrEnum):
    """``enrollments.status`` -- the enrollment lifecycle, stored not derived.

    The vocabulary exists so the table can record states the free-first flow
    will produce later (``completed`` once progress says so, ``cancelled`` on
    unenroll) without a migration. Stage 2 only ever writes ``active``.
    """

    ACTIVE = "active"
    COMPLETED = "completed"
    CANCELLED = "cancelled"


class MediaKind(StrEnum):
    """``media_assets.kind`` -- what a media asset is.

    The three kinds are ``image``, ``video``, ``document``. The set is closed
    and enforced at the database level via a ``CHECK`` constraint in the
    ``media_assets`` table.
    """

    IMAGE = "image"
    VIDEO = "video"
    DOCUMENT = "document"